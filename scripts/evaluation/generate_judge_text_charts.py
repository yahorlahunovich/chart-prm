def plot_07_multilabel_cooccurrence(df_fails: pd.DataFrame, out_path: Path) -> None:
    """Plot 7: Co-occurrence heatmap of multiple errors identified in single steps."""
    setup_plot_style()

    short_names = [
        "Incomplete Step",
        "Hallucinated Entity",
        "Arithmetic Mistake",
        "Axis / Layout Misread",
        "Wrong Ranking",
        "Wrong Series / Color",
        "Bad Comparison",
        "Wrong Numeric Read",
        "Logic Inconsistency",
    ]
    top_cats = [r[0] for r in RULES]

    binary_records = []
    for _, row in df_fails.iterrows():
        text = str(row["analysis"])
        hits = extract_multi_categories(text)
        binary_records.append({c: int(c in hits) for c in top_cats})

    df_bin = pd.DataFrame(binary_records)
    cooccur = df_bin.T.dot(df_bin)
    cooccur.index = short_names
    cooccur.columns = short_names

    # Mask diagonal for maximum contrast of co-occurring interactions
    mask = np.eye(len(cooccur), dtype=bool)

    fig, ax = plt.subplots(figsize=(8.5, 6.5))
    sns.heatmap(
        cooccur,
        annot=True,
        fmt="d",
        cmap="Purples",
        mask=mask,
        cbar_kws={"label": "Co-Occurring Diagnoses (Count)"},
        ax=ax,
        linewidths=0.5,
        annot_kws={"size": 8.5},
    )

    ax.set_title("Co-Occurrence of Error Causes Diagnosed in Judge Feedback", fontsize=12, fontweight="bold", pad=12)
    ax.set_xticklabels(ax.get_xticklabels(), rotation=35, ha="right", fontsize=8.5)
    ax.set_yticklabels(ax.get_yticklabels(), rotation=0, fontsize=8.5)

    fig.tight_layout()
    fig.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Generated {out_path}")


def plot_08_semantic_embedding_projection(
    df_fails: pd.DataFrame, emb_path: Path, out_path: Path
) -> None:
    """Plot 8: 2D projection of MiniLM sentence embeddings of judge critiques."""
    setup_plot_style()

    if not emb_path.exists():
        print(f"Embedding file {emb_path} not found. Skipping embedding plot.")
        return

    emb = np.load(emb_path)
    if len(emb) != len(df_fails):
        print(f"Embedding length {len(emb)} != df length {len(df_fails)}. Skipping.")
        return

    try:
        import umap
        reducer = umap.UMAP(n_neighbors=25, min_dist=0.25, metric="cosine", random_state=42)
        proj_name = "UMAP"
        coords = reducer.fit_transform(emb)
    except ImportError:
        from sklearn.manifold import TSNE
        reducer = TSNE(n_components=2, perplexity=30, random_state=42, init="pca", learning_rate="auto")
        proj_name = "t-SNE"
        coords = reducer.fit_transform(emb)

    df_plot = df_fails.copy()
    df_plot["x"] = coords[:, 0]
    df_plot["y"] = coords[:, 1]

    top_cats = [
        "Axis / layout / chart-structure misread",
        "Wrong series / color / legend identity",
        "Hallucinated entity / label not on chart",
        "Wrong ranking / extremum (highest/lowest/second)",
        "Logic inconsistency / false conclusion",
        "Wrong numeric value read from chart",
    ]
    df_plot["plot_category"] = df_plot["error_category_label"].apply(
        lambda c: c if c in top_cats else "Other / Minor Causes"
    )

    fig, ax = plt.subplots(figsize=(9.5, 6))

    scatter_palette = {cat: TAXONOMY_COLORS.get(cat, "#BAB0AC") for cat in top_cats}
    scatter_palette["Other / Minor Causes"] = "#BAB0AC"

    sns.scatterplot(
        data=df_plot,
        x="x",
        y="y",
        hue="plot_category",
        palette=scatter_palette,
        alpha=0.65,
        s=28,
        edgecolor="none",
        ax=ax,
    )

    # Compute and annotate cluster centroids with specific non-overlapping offsets
    short_labels = {
        "Axis / layout / chart-structure misread": "Axis / Layout Misread",
        "Wrong series / color / legend identity": "Wrong Series / Color / Legend",
        "Hallucinated entity / label not on chart": "Hallucinated Entity / Label",
        "Wrong ranking / extremum (highest/lowest/second)": "Wrong Ranking / Extremum",
        "Logic inconsistency / false conclusion": "Logic Inconsistency",
        "Wrong numeric value read from chart": "Wrong Numeric Value",
    }

    # Offsets in data coordinates to prevent annotation overlap
    label_offsets = {
        "Wrong Ranking / Extremum": (0.0, 0.4),
        "Wrong Numeric Value": (0.0, 0.35),
        "Logic Inconsistency": (-0.8, -0.35),
        "Hallucinated Entity / Label": (0.0, 0.0),
        "Axis / Layout Misread": (0.0, -0.3),
        "Wrong Series / Color / Legend": (0.0, 0.6),
    }

    for cat in top_cats:
        cat_df = df_plot[df_plot["plot_category"] == cat]
        if len(cat_df) > 0:
            cx, cy = cat_df["x"].median(), cat_df["y"].median()
            lbl = short_labels.get(cat, cat.split("/")[0].strip())
            ox, oy = label_offsets.get(lbl, (0.0, 0.0))
            ax.annotate(
                lbl,
                xy=(cx, cy),
                xytext=(cx + ox, cy + oy),
                fontsize=8.5,
                fontweight="bold",
                ha="center",
                va="center",
                bbox=dict(
                    boxstyle="round,pad=0.25",
                    facecolor="white",
                    edgecolor=TAXONOMY_COLORS.get(cat, "#333"),
                    alpha=0.92,
                    linewidth=1.2,
                ),
                arrowprops=dict(
                    arrowstyle="-",
                    color=TAXONOMY_COLORS.get(cat, "#333"),
                    lw=0.8,
                    alpha=0.6,
                ) if (ox != 0 or oy != 0) else None,
            )

    ax.set_title(f"Semantic Embedding Space of 2,920 Meta PRM Judge Critiques ({proj_name})", fontsize=12.5, fontweight="bold", pad=12)
    ax.set_xlabel(f"{proj_name} Dimension 1", fontsize=10)
    ax.set_ylabel(f"{proj_name} Dimension 2", fontsize=10)
    ax.legend(bbox_to_anchor=(1.02, 1), loc="upper left", frameon=False, fontsize=8.5)
    ax.grid(True, linestyle="--", alpha=0.25)

    fig.tight_layout()
    fig.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Generated {out_path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--eval-jsonl",
        type=Path,
        default=REPO_ROOT / "experiments/001_500_reasoning/data/evaluated_rollouts.jsonl",
    )
    parser.add_argument(
        "--fails-csv",
        type=Path,
        default=REPO_ROOT / "experiments/001_500_reasoning/judge_error_analysis/fail_analyses_categorized.csv",
    )
    parser.add_argument(
        "--embeddings-npy",
        type=Path,
        default=REPO_ROOT / "experiments/001_500_reasoning/judge_error_analysis/fail_analysis_embeddings.npy",
    )
    parser.add_argument(
        "--meta-json",
        type=Path,
        default=REPO_ROOT / "data/CharXiv/data/image_metadata_val.json",
    )
    parser.add_argument(
        "--chart-types-json",
        type=Path,
        default=REPO_ROOT / "data/CharXiv/data/chart_types_val.json",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=REPO_ROOT / "charts",
    )
    args = parser.parse_args()

    out_dir: Path = args.output_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"Loading evaluated rollouts from {args.eval_jsonl}...")
    df_all = load_all_evaluations(args.eval_jsonl, args.meta_json, args.chart_types_json)
    print(f"Loaded {len(df_all)} total step evaluations.")

    print(f"Loading categorized fail analyses from {args.fails_csv}...")
    if args.fails_csv.exists():
        df_fails = pd.read_csv(args.fails_csv)
    else:
        df_fails = df_all[df_all["score"] == 0].copy()

    # Merge domain and chart_type into df_fails if missing
    if "domain" not in df_fails.columns or "chart_type" not in df_fails.columns:
        df_meta_merge = df_all[["question_id", "rollout_index", "step_index", "domain", "chart_type"]].drop_duplicates()
        df_fails["question_id"] = df_fails["question_id"].astype(str)
        df_meta_merge["question_id"] = df_meta_merge["question_id"].astype(str)
        df_fails = df_fails.merge(
            df_meta_merge,
            on=["question_id", "rollout_index", "step_index"],
            how="left",
            suffixes=("", "_meta")
        )
        if "domain_meta" in df_fails.columns:
            df_fails["domain"] = df_fails["domain_meta"].fillna("Unknown")
        if "chart_type_meta" in df_fails.columns:
            df_fails["chart_type"] = df_fails["chart_type_meta"].fillna("Unknown")

    print("Generating charts in:", out_dir)
    plot_01_error_taxonomy(df_fails, out_dir / "judge_01_error_taxonomy.png")
    plot_02_error_by_step_depth(df_fails, out_dir / "judge_02_error_by_step_depth.png")
    plot_03_critique_length_distribution(df_all, out_dir / "judge_03_critique_length_distribution.png")
    plot_04_top_keywords_per_category(df_fails, out_dir / "judge_04_top_keywords_per_category.png")
    plot_05_error_taxonomy_by_domain(df_fails, out_dir / "judge_05_error_taxonomy_by_domain.png")
    plot_06_error_taxonomy_by_chart_type(df_fails, out_dir / "judge_06_error_taxonomy_by_chart_type.png")
    plot_07_multilabel_cooccurrence(df_fails, out_dir / "judge_07_multilabel_cooccurrence.png")
    plot_08_semantic_embedding_projection(df_fails, args.embeddings_npy, out_dir / "judge_08_umap_embeddings.png")
    print("All Meta judge text analysis charts generated successfully!")


if __name__ == "__main__":
    main()
