CATEGORY_ORDER = [r[0] for r in RULES] + ["other_unspecified"]
DISPLAY_MAP = {r[0]: r[1] for r in RULES}
DISPLAY_MAP["other_unspecified"] = "Other / unspecified"


def assign_primary_category(text: str) -> str:
    """Assigns the first matching rule category to a judge critique text."""
    t = text.lower()
    for key, _label, pat in RULES:
        if re.search(pat, t):
            return key
    return "other_unspecified"


def extract_multi_categories(text: str) -> List[str]:
    """Finds all matching rule categories in a judge critique text."""
    t = text.lower()
    hits = [key for key, _label, pat in RULES if re.search(pat, t)]
    return hits or ["other_unspecified"]


def load_all_evaluations(
    eval_path: Path, meta_path: Path, chart_types_path: Path
) -> pd.DataFrame:
    """Loads all rollouts and joins step evaluations with metadata."""
    with open(meta_path, "r") as f:
        meta = json.load(f)
    with open(chart_types_path, "r") as f:
        chart_types = json.load(f)

    rows = []
    with open(eval_path, "r") as f:
        for line in f:
            item = json.loads(line)
            qid = str(item.get("question_id"))
            ridx = item.get("rollout_index", 0)
            domain = meta.get(qid, {}).get("category", "Unknown").upper()
            ctypes = chart_types.get(qid, {}).get("chart_types", ["Unknown"])
            ctype = ctypes[0] if ctypes else "Unknown"

            evals = item.get("evaluations") or []
            for i, step in enumerate(evals):
                analysis = step.get("analysis", "").strip()
                score = step.get("score")
                step_idx = step.get("step_index", i)

                cat_key = assign_primary_category(analysis) if score == 0 else "valid_step"
                cat_label = DISPLAY_MAP.get(cat_key, "Valid Step") if score == 0 else "Valid Step"
                multi_cats = (
                    [DISPLAY_MAP[c] for c in extract_multi_categories(analysis)]
                    if score == 0
                    else ["Valid Step"]
                )

                rows.append({
                    "question_id": qid,
                    "rollout_index": ridx,
                    "step_index": step_idx,
                    "score": score,
                    "analysis": analysis,
                    "analysis_len": len(analysis),
                    "analysis_words": len(analysis.split()),
                    "domain": domain,
                    "chart_type": ctype,
                    "error_category_key": cat_key,
                    "error_category_label": cat_label,
                    "multi_categories": multi_cats,
                    "total_steps": len(evals),
                })

    return pd.DataFrame(rows)


def plot_01_error_taxonomy(df_fails: pd.DataFrame, out_path: Path) -> None:
    """Plot 1: Horizontal Pareto/Distribution bar chart of failure causes."""
    setup_plot_style()
    counts = df_fails["error_category_label"].value_counts()
    total = len(df_fails)
    pcts = (counts / total * 100).round(1)

    fig, ax = plt.subplots(figsize=(8.5, 4.8))
    y_pos = np.arange(len(counts))
    colors = [TAXONOMY_COLORS.get(cat, "#4C78A8") for cat in counts.index]

    ax.barh(y_pos, counts.values, color=colors, height=0.68, edgecolor="none")
    ax.set_yticks(y_pos)
    ax.set_yticklabels(counts.index, fontsize=10)
    ax.invert_yaxis()
    ax.set_xlabel("Number of Failed Reasoning Steps (Score = 0)", fontsize=11, labelpad=8)
    ax.set_title("PRM Judge (Meta muse-spark-1.1) Failure Modes Taxonomy", fontsize=13, fontweight="bold", pad=14)

    max_val = counts.max()
    for i, (n, p) in enumerate(zip(counts.values, pcts.values)):
        ax.text(
            n + max_val * 0.015,
            i,
            f"{n:,} ({p:.1f}%)",
            va="center",
            ha="left",
            fontsize=9.5,
            color="#2B2B2B",
            fontweight="bold" if p > 10 else "normal",
        )

    ax.set_xlim(0, max_val * 1.25)
    ax.grid(axis="x", linestyle="--", alpha=0.3)

    fig.tight_layout()
    fig.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Generated {out_path}")


def plot_02_error_by_step_depth(df_fails: pd.DataFrame, out_path: Path) -> None:
    """Plot 2: Evolution of error categories across reasoning step depth."""
    setup_plot_style()
    df_copy = df_fails.copy()
    df_copy["step_bucket"] = df_copy["step_index"].apply(
        lambda x: f"Step {x}" if x < 4 else "Step 4+"
    )

    top_cats = [
        "Axis / layout / chart-structure misread",
        "Wrong series / color / legend identity",
        "Hallucinated entity / label not on chart",
        "Wrong ranking / extremum (highest/lowest/second)",
        "Logic inconsistency / false conclusion",
        "Wrong numeric value read from chart",
        "Bad comparison / threshold logic",
    ]
    df_copy["cat_plot"] = df_copy["error_category_label"].apply(
        lambda c: c if c in top_cats else "Other / Minor"
    )

    pivot_counts = (
        df_copy.groupby(["step_bucket", "cat_plot"])
        .size()
        .unstack(fill_value=0)
    )
    step_order = ["Step 0", "Step 1", "Step 2", "Step 3", "Step 4+"]
    col_order = [c for c in top_cats if c in pivot_counts.columns] + ["Other / Minor"]
    pivot_counts = pivot_counts.reindex(index=step_order, columns=col_order).fillna(0)
    pivot_pct = pivot_counts.div(pivot_counts.sum(axis=1), axis=0) * 100

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(13, 5), sharey=False)
    colors_list = [TAXONOMY_COLORS.get(c, "#BAB0AC") for c in pivot_counts.columns]

    # Subplot A: Absolute Counts
    pivot_counts.plot(
        kind="bar",
        stacked=True,
        ax=ax1,
        color=colors_list,
        edgecolor="white",
        linewidth=0.5,
        width=0.65,
        legend=False,
    )
    ax1.set_title("(A) Absolute Error Counts by Step Depth", fontsize=11.5, fontweight="bold")
    ax1.set_xlabel("Reasoning Step", fontsize=10.5)
    ax1.set_ylabel("Count of Failed Steps", fontsize=10.5)
    ax1.set_xticklabels(step_order, rotation=0)
    ax1.grid(axis="y", linestyle="--", alpha=0.3)

    # Subplot B: Relative Percentage
    pivot_pct.plot(
        kind="bar",
        stacked=True,
        ax=ax2,
        color=colors_list,
        edgecolor="white",
        linewidth=0.5,
        width=0.65,
        legend=False,
    )
    ax2.set_title("(B) Proportional Failure Composition (%)", fontsize=11.5, fontweight="bold")
    ax2.set_xlabel("Reasoning Step", fontsize=10.5)
    ax2.set_ylabel("Share of Step Errors (%)", fontsize=10.5)
    ax2.set_ylim(0, 100)
    ax2.set_xticklabels(step_order, rotation=0)
    ax2.grid(axis="y", linestyle="--", alpha=0.3)

    # Place unified legend below the plots
    handles, labels = ax1.get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.16),
        ncol=3,
        frameon=False,
        fontsize=8.5,
    )

    fig.suptitle("Evolution of PRM Judge Error Classifications Across Reasoning Steps", fontsize=13, fontweight="bold", y=1.02)
    fig.tight_layout()
    fig.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Generated {out_path}")


