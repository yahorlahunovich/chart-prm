def plot_04_top_keywords_per_category(df_fails: pd.DataFrame, out_path: Path) -> None:
    """Plot 4: Multi-panel faceted bar chart of top TF-IDF diagnostic vocabulary."""
    setup_plot_style()

    top_6_categories = [
        "Axis / layout / chart-structure misread",
        "Wrong series / color / legend identity",
        "Hallucinated entity / label not on chart",
        "Wrong ranking / extremum (highest/lowest/second)",
        "Logic inconsistency / false conclusion",
        "Wrong numeric value read from chart",
    ]

    short_titles = {
        "Axis / layout / chart-structure misread": "Axis / Layout Misread",
        "Wrong series / color / legend identity": "Wrong Series / Color / Legend",
        "Hallucinated entity / label not on chart": "Hallucinated Entity / Label",
        "Wrong ranking / extremum (highest/lowest/second)": "Wrong Ranking / Extremum",
        "Logic inconsistency / false conclusion": "Logic Inconsistency / False Conclusion",
        "Wrong numeric value read from chart": "Wrong Numeric Value Read",
    }

    fig, axes = plt.subplots(2, 3, figsize=(13, 7.5), sharex=False)
    axes = axes.flatten()

    custom_stops = {
        "step", "chart", "incorrect", "correct", "does", "factually",
        "shows", "ground", "truth", "fails", "instead", "value", "values",
        "stated", "claim", "claims", "answer"
    }

    for idx, cat_label in enumerate(top_6_categories):
        ax = axes[idx]
        subset = df_fails[df_fails["error_category_label"] == cat_label]["analysis"].dropna().astype(str)

        if len(subset) > 0:
            vec = TfidfVectorizer(
                max_features=2000,
                ngram_range=(1, 2),
                stop_words="english",
                min_df=2,
            )
            x_mat = vec.fit_transform(subset)
            feature_names = np.array(vec.get_feature_names_out())
            mean_tfidf = np.asarray(x_mat.mean(axis=0)).ravel()

            valid_mask = np.array([f not in custom_stops and len(f) > 2 for f in feature_names])
            filtered_names = feature_names[valid_mask]
            filtered_scores = mean_tfidf[valid_mask]

            top_indices = filtered_scores.argsort()[::-1][:7]
            terms = filtered_names[top_indices]
            scores = filtered_scores[top_indices]

            y_pos = np.arange(len(terms))
            bar_color = TAXONOMY_COLORS.get(cat_label, "#4C78A8")
            ax.barh(y_pos, scores, color=bar_color, height=0.65, alpha=0.85)
            ax.set_yticks(y_pos)
            ax.set_yticklabels(terms, fontsize=9.5)
            ax.invert_yaxis()
            ax.set_title(f"{short_titles[cat_label]} (n={len(subset)})", fontsize=10.5, fontweight="bold", pad=8)
            ax.grid(axis="x", linestyle="--", alpha=0.25)
            ax.set_xlabel("Mean TF-IDF", fontsize=8.5)

    fig.suptitle("Diagnostic Keywords Extracted from Meta PRM Judge Critiques", fontsize=13, fontweight="bold", y=0.99)
    fig.tight_layout(rect=[0, 0.03, 1, 0.95])
    fig.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"Generated {out_path}")


