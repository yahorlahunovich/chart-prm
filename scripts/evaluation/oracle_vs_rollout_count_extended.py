#!/usr/bin/env python3
"""
oracle_vs_rollout_count_extended.py

Extends experiment 013's oracle-vs-K diagnostic from K=1..5 to K=1..10, using
the extra rollouts (indices 5-9) generated by the qwen-vl-extra-rollouts
Kaggle job. Answers the question that motivated generating them: does the
oracle ceiling (does *any* rollout have the correct final answer) keep rising
past K=5's 53.4%, or does it flatten?

Indices 0-4 come from experiment 001's cleaned rollouts (already-parsed
model_final_answer). Indices 5-9 come from data/generated_extra_rollouts.jsonl
(raw model_output text) and are parsed with the exact same "Step 1:" /
"Final Answer:" extraction convention as scripts/data_prep/clean_dataset.py,
so a rollout that wouldn't have survived the original cleaning pipeline is
treated the same way here (dropped, not counted as a correct-or-incorrect
answer).

No GPU, no API calls -- pure re-analysis of already-generated data.
"""

from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from chart_prm.text_match import answers_match  # noqa: E402


def extract_final_answer(model_output: str) -> str | None:
    """Same convention as clean_dataset.py's parse_model_output: require both
    delimiters, extract everything after the last 'Final Answer:'."""
    if "Step 1:" not in model_output or "Final Answer:" not in model_output:
        return None
    match = re.search(r"Final Answer:(.*?)(?:$)", model_output, flags=re.IGNORECASE | re.DOTALL)
    if not match:
        return None
    return match.group(1).strip()


def main() -> None:
    base_dir = Path(__file__).resolve().parents[2]
    cleaned_path = base_dir / "experiments/001_500_reasoning/data/001_500_reasoning_cleaned.jsonl"
    extra_path = base_dir / "experiments/016_extra_rollouts/data/generated_extra_rollouts.jsonl"

    by_question: dict[str, dict[int, tuple[str, str]]] = defaultdict(dict)

    with cleaned_path.open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            data = json.loads(line)
            qid = str(data["question_id"])
            ridx = data["rollout_index"]
            by_question[qid][ridx] = (data.get("ground_truth", ""), data.get("model_final_answer", ""))

    n_extra_rows = 0
    n_extra_parsed = 0
    with extra_path.open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            n_extra_rows += 1
            data = json.loads(line)
            qid = str(data["question_id"])
            ridx = data["rollout_index"]
            final_answer = extract_final_answer(data.get("model_output", "") or "")
            if final_answer is None:
                continue
            n_extra_parsed += 1
            by_question[qid][ridx] = (data.get("ground_truth", ""), final_answer)

    print(f"Extra rollouts read: {n_extra_rows}, parsed (Step 1: + Final Answer: present): {n_extra_parsed}")

    full_questions = {
        qid: rollouts for qid, rollouts in by_question.items() if set(rollouts) == set(range(10))
    }
    n = len(full_questions)
    print(f"Questions with all 10 rollout indices (0-9) present and parseable: {n}")

    print(f"\n{'K (rollouts considered)':<28}{'Oracle accuracy':>18}{'Marginal gain':>16}")
    prev = None
    results = {}
    for k in range(1, 11):
        correct = 0
        for qid, rollouts in full_questions.items():
            for idx in range(k):
                gt, pred = rollouts[idx]
                if answers_match(gt, pred):
                    correct += 1
                    break
        acc = correct / n
        results[k] = acc
        gain = f"{acc - prev:+.1%}" if prev is not None else "--"
        print(f"{k:<28}{acc:>17.1%}{gain:>16}")
        prev = acc

    out_path = base_dir / "experiments/016_extra_rollouts/data/oracle_vs_rollout_count_extended.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps({"n_questions": n, "oracle_by_k": results}, indent=2), encoding="utf-8")
    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    main()
